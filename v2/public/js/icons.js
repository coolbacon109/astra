// 'anime' is Gojo: a transparent sticker PNG made from the user's sketch (assets/gojo.png), sized small via .icon-anime.
export function svgIcon(name, extraClass = '') {
  if (name === 'anime') return `<img class="icon icon-anime${extraClass ? ' ' + extraClass : ''}" src="/assets/gojo.png" alt="anime" draggable="false" />`;
  const body = PATHS[name] || PATHS.globe;
  const cls = `icon icon-${name}${extraClass ? ' ' + extraClass : ''}`;
  return `<svg class="${cls}" ${BASE}>${body}</svg>`;
}

