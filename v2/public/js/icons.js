// Swap the static rail glyphs for the shared set (single source of truth).
export function applyRailIcons(root = document) {
  Object.entries(RAIL_MAP).forEach(([route, name]) => {
    const btn = root.querySelector(`.rail-btn[data-route="${route}"]`);
    if (btn) btn.innerHTML = svgIcon(name);
  });
  const out = root.getElementById ? root.getElementById('railLogoutBtn') : root.querySelector('#railLogoutBtn');
  if (out) out.innerHTML = svgIcon('logout');
}
